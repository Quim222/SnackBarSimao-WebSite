@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly language = signal<Language>(
    (localStorage.getItem('snack-bar-language') as Language) || 'pt',
  );
  readonly dictionaries: Record<Language, Record<string, string>> = { pt: fallback, en: english };
  setLanguage(language: Language) {
    this.language.set(language);
    localStorage.setItem('snack-bar-language', language);
    document.documentElement.lang = language === 'pt' ? 'pt-PT' : 'en';
  }
  t(key: string) {
    return this.dictionaries[this.language()][key] ?? fallback[key] ?? key;
  }
}
@Pipe({ name: 't', pure: false })
export class TranslatePipe implements PipeTransform {
  constructor(private readonly i18n: I18nService) {}
  transform(key: string) {
    return this.i18n.t(key);
  }
}
